// Preset returns one palette by name, case-insensitively.
func PresetNamed(name string) (Preset, bool) {
	for _, p := range Presets {
		if equalFold(p.Name, name) {
			return p, true
		}
	}
	return Preset{}, false
}

// PresetNames lists the names, for an error message and for docs.
func PresetNames() []string {
	out := make([]string, 0, len(Presets))
	for _, p := range Presets {
		out = append(out, p.Name)
	}
	return out
}

// equalFold avoids pulling strings into a package that otherwise only does maths.
func equalFold(a, b string) bool {
	if len(a) != len(b) {
		return false
	}
	for i := 0; i < len(a); i++ {
		ca, cb := a[i], b[i]
		if 'A' <= ca && ca <= 'Z' {
			ca += 'a' - 'A'
		}
		if 'A' <= cb && cb <= 'Z' {
			cb += 'a' - 'A'
		}
		if ca != cb {
			return false
		}
	}
	return true
}
